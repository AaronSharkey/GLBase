inline void ModelLoadingExample::render(float deltaTime) {
    camera.updateCameraPositions(deltaTime);
    // Set shared camera matrices
    const glm::mat4 view = camera.getViewMatrix();
    const glm::mat4 projection = camera.getProjectionMatrix();

    modelLoadingShader.use();

    modelLoadingShader.setMat4("view", view);
    modelLoadingShader.setMat4("projection", projection);

    const auto currentTime = static_cast<float>(glfwGetTime());

    const glm::mat4 objectModel = Transform()
                                  .setPosition(glm::vec3(0.0f, -1.0f, -5.0f))
                                  .setRotation(glm::vec3(0.0f, currentTime, 0.0f))
                                  .setScale(glm::vec3(0.05f, 0.05f, 0.05f))
                                  .getTransform();

    modelLoadingShader.setMat4("model", objectModel);

    ourModel.Draw(modelLoadingShader);

}